// fireredsim: generates platform/bios_affine_trig.h.
//
// mGBA's HLE BIOS (third_party/mgba/src/gba/bios.c, _BgAffineSet and
// _ObjAffineSet) computes the affine matrices with single-precision floats:
//     theta = (angle >> 8) / 128.f * M_PI;   a = d = cosf(theta); b = c = sinf(theta);
// The oracle is a 64-bit x86 build of mGBA using the host glibc's cosf/sinf.
// To reproduce its results bit for bit from the 32-bit simulator, the 256
// possible cosf/sinf values are computed once by this program, built for and
// run on the same 64-bit host, and embedded as IEEE-754 bit patterns.
//
//   cc -O2 -o gen_affine_trig gen_affine_trig.c -lm && ./gen_affine_trig > ../bios_affine_trig.h
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

static uint32_t bits(float f)
{
    uint32_t u;
    memcpy(&u, &f, sizeof u);
    return u;
}

int main(void)
{
    printf("// Generated by platform/tools/gen_affine_trig.c on an x86-64 glibc host. Do not edit.\n");
    printf("// cosf/sinf of theta = (k / 128.f) * M_PI (float), k = angle >> 8, as in mGBA's HLE BIOS.\n");
    printf("static const uint32_t sAffineCos[256] = {\n");
    for (unsigned k = 0; k < 256; k++) {
        volatile uint32_t kk = k;
        float theta = kk / 128.f * M_PI;
        printf("%s0x%08X,%s", (k % 8) ? "" : "    ", bits(cosf(theta)), (k % 8 == 7) ? "\n" : " ");
    }
    printf("};\nstatic const uint32_t sAffineSin[256] = {\n");
    for (unsigned k = 0; k < 256; k++) {
        volatile uint32_t kk = k;
        float theta = kk / 128.f * M_PI;
        printf("%s0x%08X,%s", (k % 8) ? "" : "    ", bits(sinf(theta)), (k % 8 == 7) ? "\n" : " ");
    }
    printf("};\n");
    return 0;
}
